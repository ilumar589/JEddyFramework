package dev.jeddy.cooker.level;

import dev.jeddy.asset.AssetPaths;
import dev.jeddy.asset.format.LevelData;

import java.io.IOException;
import java.lang.foreign.MemorySegment;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.stream.Stream;

/**
 * Scene bindings (DESIGN §22, D110): for a level {@code levels/crypt.jlevel} a Java class {@code
 * CryptLevel} with the stable object ids of its named placements, lights, spawns and triggers as
 * constants ({@code SPAWN_PARTY_START}, {@code TRIGGER_ENTRANCE}, {@code PLACEMENT_ALTAR}, {@code
 * LIGHT_BRAZIER}) and its asset path, so game code names what the editor placed and the compiler
 * checks it; {@code LevelLoader.rootOf(id)} turns an id into the entity. The {@code
 * generateLevelBindings} Gradle task runs {@code jeddy-cook bindings} before {@code compileJava}.
 *
 * <p>Names become identifiers: upper case, runs of other characters to one underscore, a leading
 * digit prefixed; objects without a name are skipped; two objects that map to the same identifier
 * get their id appended.
 *
 * <p>Thread ownership: any thread; stateless.
 */
public final class LevelBindings {
    private LevelBindings() {}

    /**
     * Writes a binding for every {@code .jlevel} under {@code source} into {@code out} (package
     * directories created). Returns the number written.
     */
    public static int generateAll(Path source, Path out, String pkg) throws IOException {
        List<Path> levels = new ArrayList<>();
        try (Stream<Path> walk = Files.walk(source)) {
            walk.filter(p -> p.toString().toLowerCase(Locale.ROOT).endsWith(".jlevel"))
                    .forEach(levels::add);
        }
        levels.sort(null);
        Path dir = out.resolve(pkg.replace('.', '/'));
        Files.createDirectories(dir);
        for (Path file : levels) {
            String assetPath =
                    AssetPaths.normalize(source.relativize(file).toString().replace('\\', '/'));
            LevelData level = LevelData.read(MemorySegment.ofArray(Files.readAllBytes(file)));
            String className = className(file.getFileName().toString());
            byte[] text =
                    generate(level, assetPath, pkg, className).getBytes(StandardCharsets.UTF_8);
            Path target = dir.resolve(className + ".java");
            if (!Files.exists(target) || !Arrays.equals(text, Files.readAllBytes(target))) {
                Files.write(target, text); // unchanged files keep their timestamp (javac, Gradle)
            }
        }
        return levels.size();
    }

    /**
     * {@code crypt.jlevel} → {@code CryptLevel}; {@code old-tower.jlevel} → {@code OldTowerLevel}.
     */
    public static String className(String fileName) {
        String base = fileName;
        int dot = base.lastIndexOf('.');
        if (dot > 0) {
            base = base.substring(0, dot);
        }
        StringBuilder b = new StringBuilder();
        boolean upper = true;
        for (int i = 0; i < base.length(); i++) {
            char c = base.charAt(i);
            if (Character.isLetterOrDigit(c)) {
                b.append(upper ? Character.toUpperCase(c) : c);
                upper = false;
            } else {
                upper = true;
            }
        }
        if (b.isEmpty() || Character.isDigit(b.charAt(0))) {
            b.insert(0, "L");
        }
        return b + "Level";
    }

    /** The source of the binding class. */
    public static String generate(LevelData level, String assetPath, String pkg, String className) {
        StringBuilder b = new StringBuilder();
        if (!pkg.isEmpty()) {
            b.append("package ").append(pkg).append(";\n\n");
        }
        b.append("/**\n * The objects of {@code ")
                .append(assetPath)
                .append("} by their stable ids; generated by the Jeddy\n");
        b.append(
                " * cooker from the level file, do not edit (DESIGN §22, D110). {@code"
                        + " LevelLoader.rootOf(id)} gives\n");
        b.append(
                " * a placement's entity; spawns and triggers are read from the {@code LevelData}"
                        + " by id. Only\n");
        b.append(
                " * objects whose name is unique among their kind get a constant: a repeated name"
                        + " (a prefab's,\n");
        b.append(" * usually) is not a designer's name for one object.\n */\n");
        b.append("public final class ").append(className).append(" {\n");
        b.append("    /** The level's asset path. */\n");
        b.append("    public static final String PATH = \"").append(assetPath).append("\";\n\n");
        b.append("    private ").append(className).append("() {}\n");
        List<String> skipped = new ArrayList<>();
        kind(
                b,
                skipped,
                "PLACEMENT_",
                "placement",
                level.placementCount(),
                level::placementName,
                level::placementId);
        kind(b, skipped, "LIGHT_", "light", level.lightCount(), level::lightName, level::lightId);
        kind(b, skipped, "SPAWN_", "spawn", level.spawnCount(), level::spawnName, level::spawnId);
        kind(
                b,
                skipped,
                "TRIGGER_",
                "trigger",
                level.triggerCount(),
                level::triggerName,
                level::triggerId);
        if (!skipped.isEmpty()) {
            b.append("\n    // Repeated names, no constant: ")
                    .append(String.join(", ", skipped))
                    .append("\n");
        }
        b.append("}\n");
        return b.toString();
    }

    private static void kind(
            StringBuilder b,
            List<String> skipped,
            String prefix,
            String what,
            int count,
            java.util.function.IntFunction<String> name,
            java.util.function.IntUnaryOperator id) {
        Map<String, Integer> uses = new LinkedHashMap<>();
        for (int i = 0; i < count; i++) {
            String n = name.apply(i);
            if (n != null && !n.isBlank()) {
                uses.merge(prefix + identifier(n), 1, Integer::sum);
            }
        }
        for (int i = 0; i < count; i++) {
            String n = name.apply(i);
            if (n == null || n.isBlank()) {
                continue;
            }
            String ident = prefix + identifier(n);
            if (uses.get(ident) > 1) {
                if (!skipped.contains(ident)) {
                    skipped.add(ident);
                }
                continue;
            }
            b.append("\n    /** The ")
                    .append(what)
                    .append(" \"")
                    .append(n.replace("*/", "* /"))
                    .append("\". */\n");
            b.append("    public static final int ")
                    .append(ident)
                    .append(" = ")
                    .append(id.applyAsInt(i))
                    .append(";\n");
        }
    }

    /** Upper snake case of a name: {@code "party start"} → {@code PARTY_START}. */
    public static String identifier(String name) {
        StringBuilder b = new StringBuilder();
        boolean gap = false;
        for (int i = 0; i < name.length(); i++) {
            char c = name.charAt(i);
            if (Character.isLetterOrDigit(c) && c < 0x80) {
                if (gap && !b.isEmpty()) {
                    b.append('_');
                }
                if (Character.isUpperCase(c)
                        && i > 0
                        && Character.isLowerCase(name.charAt(i - 1))) {
                    b.append('_'); // a camelCase boundary
                }
                b.append(Character.toUpperCase(c));
                gap = false;
            } else {
                gap = true;
            }
        }
        if (b.isEmpty()) {
            b.append("UNNAMED");
        }
        if (Character.isDigit(b.charAt(0))) {
            b.insert(0, '_');
        }
        return b.toString();
    }
}
