package dev.jeddy.components.processor;

import dev.jeddy.components.processor.Model.Behaviour;
import dev.jeddy.components.processor.Model.Component;
import dev.jeddy.components.processor.Model.Param;
import dev.jeddy.components.processor.Model.ParamKind;
import dev.jeddy.components.processor.Model.Phase;
import dev.jeddy.components.processor.Model.Singleton;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Emits the game's registry (DESIGN §22, D107, D108): the stores, the singletons, one loop per
 * behaviour, the parallel groups as job graphs, and the phase entry points.
 *
 * <p>Thread ownership: the compiler's processing thread.
 */
final class RegistryGen {
    private RegistryGen() {}

    static String registry(Model m) {
        StringBuilder b = new StringBuilder();
        if (!m.registryPackage.isEmpty()) {
            b.append("package ").append(m.registryPackage).append(";\n\n");
        }
        b.append("import dev.jeddy.components.SnapshotReader;\n");
        b.append("import dev.jeddy.components.SnapshotWriter;\n");
        b.append("import dev.jeddy.components.Store;\n");
        b.append("import dev.jeddy.core.job.JobGraph;\n");
        b.append("import dev.jeddy.core.job.JobKernel;\n");
        b.append("import dev.jeddy.core.job.JobSystem;\n");
        b.append("import dev.jeddy.scene.EntityPool;\n\n");
        b.append(
                "/**\n"
                        + " * The component registry of this game: every store, the singletons the"
                        + " behaviours take, and the\n");
        b.append(
                " * phase entry points; generated by the Jeddy component processor, do not edit"
                        + " (DESIGN §22).\n");
        b.append(
                " *\n"
                    + " * <p>Thread ownership: the game thread; parallel behaviours run on the job"
                    + " system inside the\n");
        b.append(" * phase calls.\n */\n");
        b.append("public final class ").append(m.registryName).append(" {\n");
        b.append("    /** Rows each store starts with. */\n");
        b.append("    public static final int CAPACITY = ").append(m.capacity).append(";\n\n");
        b.append("    private final EntityPool entities;\n");
        b.append("    private final JobSystem jobs;\n");
        for (Component c : m.components) {
            b.append("    private final ")
                    .append(c.qualifiedStore())
                    .append(" ")
                    .append(c.fieldName())
                    .append(";\n");
        }
        b.append("    private final Store[] stores;\n");
        for (Singleton s : m.singletons) {
            b.append("    private final ").append(s.type).append(" ").append(s.field).append(";\n");
        }
        b.append("    private float dt;\n    private float alpha;\n\n");
        // Views and kernels.
        for (Behaviour bh : m.behaviours) {
            int i = 0;
            for (Param p : bh.params) {
                if (p.kind == ParamKind.VIEW || p.kind == ParamKind.MUT) {
                    String type =
                            p.kind == ParamKind.MUT
                                    ? p.component.qualifiedMut()
                                    : p.component.qualifiedView();
                    if (bh.parallel) {
                        b.append("    private final ")
                                .append(type)
                                .append("[] ")
                                .append(viewField(bh, i))
                                .append(";\n");
                    } else {
                        b.append("    private final ")
                                .append(type)
                                .append(" ")
                                .append(viewField(bh, i))
                                .append(" = new ")
                                .append(type)
                                .append("();\n");
                    }
                }
                i++;
            }
            if (bh.parallel) {
                b.append("    private Store ").append(bh.id()).append("_drive;\n");
                b.append("    private final JobKernel ")
                        .append(bh.id())
                        .append("_kernel = this::")
                        .append(bh.id())
                        .append("_range;\n");
                b.append("    private final int ").append(bh.id()).append("_node;\n");
            }
        }
        // Parallel groups: maximal runs of consecutive parallel behaviours within a stage.
        Map<String, List<Behaviour>> groups = new LinkedHashMap<>();
        for (Phase phase : new Phase[] {Phase.FIXED_UPDATE, Phase.UPDATE}) {
            int g = 0;
            for (int stage : m.stages(phase)) {
                for (List<Behaviour> run : runs(m.ofStage(phase, stage))) {
                    if (run.get(0).parallel) {
                        String name = phase.json + "Group" + g++;
                        groups.put(name, run);
                        b.append("    private final JobGraph ")
                                .append(name)
                                .append(" = new JobGraph();\n");
                    }
                }
            }
        }
        // Constructor.
        b.append(
                "\n"
                    + "    /** Creates the stores (registered with {@code entities}) and keeps the"
                    + " singletons, which come in alphabetical order of their types' simple names;"
                    + " {@code jobs} may be null, then parallel behaviours run inline. */\n");
        b.append("    public ")
                .append(m.registryName)
                .append("(EntityPool entities, JobSystem jobs");
        for (Singleton s : m.singletons) {
            b.append(", ").append(s.type).append(" ").append(s.field);
        }
        b.append(") {\n        this.entities = entities;\n        this.jobs = jobs;\n");
        for (Singleton s : m.singletons) {
            b.append("        this.").append(s.field).append(" = ").append(s.field).append(";\n");
        }
        for (Component c : m.components) {
            b.append("        ")
                    .append(c.fieldName())
                    .append(" = new ")
                    .append(c.qualifiedStore())
                    .append("(entities, CAPACITY);\n");
        }
        b.append("        stores = new Store[] {");
        for (int i = 0; i < m.components.size(); i++) {
            b.append(i > 0 ? ", " : "").append(m.components.get(i).fieldName());
        }
        b.append("};\n");
        boolean anyParallel = false;
        for (Behaviour bh : m.behaviours) {
            anyParallel |= bh.parallel;
        }
        if (anyParallel) {
            b.append("        int slots = jobs == null ? 1 : jobs.threadSlots();\n");
            for (Behaviour bh : m.behaviours) {
                if (!bh.parallel) {
                    continue;
                }
                int i = 0;
                for (Param p : bh.params) {
                    if (p.kind == ParamKind.VIEW || p.kind == ParamKind.MUT) {
                        String type =
                                p.kind == ParamKind.MUT
                                        ? p.component.qualifiedMut()
                                        : p.component.qualifiedView();
                        b.append("        ")
                                .append(viewField(bh, i))
                                .append(" = new ")
                                .append(type)
                                .append("[slots];\n");
                        b.append("        for (int t = 0; t < slots; t++) {\n            ")
                                .append(viewField(bh, i))
                                .append("[t] = new ")
                                .append(type)
                                .append("();\n        }\n");
                    }
                    i++;
                }
            }
            for (Map.Entry<String, List<Behaviour>> g : groups.entrySet()) {
                List<Behaviour> run = g.getValue();
                for (int j = 0; j < run.size(); j++) {
                    Behaviour bh = run.get(j);
                    b.append("        ")
                            .append(bh.id())
                            .append("_node = ")
                            .append(g.getKey())
                            .append(".add(")
                            .append(bh.id())
                            .append("_kernel, 0, ")
                            .append(bh.grain);
                    for (int k = 0; k < j; k++) {
                        if (run.get(k).conflictsWith(bh)) {
                            b.append(", ").append(run.get(k).id()).append("_node");
                        }
                    }
                    b.append(");\n");
                }
            }
        }
        b.append("    }\n\n");
        // Accessors.
        b.append("    public EntityPool entities() {\n        return entities;\n    }\n\n");
        b.append(
                "    /** The job system, or null. */\n"
                        + "    public JobSystem jobs() {\n"
                        + "        return jobs;\n"
                        + "    }\n\n");
        for (Component c : m.components) {
            b.append("    public ")
                    .append(c.qualifiedStore())
                    .append(" ")
                    .append(c.fieldName())
                    .append("() {\n        return ")
                    .append(c.fieldName())
                    .append(";\n    }\n\n");
        }
        b.append(
                "    /** Every store, in schema order; do not modify. */\n"
                        + "    public Store[] stores() {\n"
                        + "        return stores;\n"
                        + "    }\n\n");
        b.append(
                "    /** The store of the component named {@code name}, or null. */\n"
                        + "    public Store store(String name) {\n"
                        + "        return switch (name) {\n");
        for (Component c : m.components) {
            b.append("            case \"")
                    .append(c.name)
                    .append("\" -> ")
                    .append(c.fieldName())
                    .append(";\n");
        }
        b.append("            default -> null;\n        };\n    }\n\n");
        b.append(
                "    /** Whether {@code entity} has any component. */\n"
                        + "    public boolean hasAny(int entity) {\n");
        b.append(
                "        for (Store s : stores) {\n"
                        + "            if (s.has(entity)) {\n"
                        + "                return true;\n"
                        + "            }\n"
                        + "        }\n"
                        + "        return false;\n"
                        + "    }\n\n");
        // Phases.
        tickPhase(b, m, Phase.FIXED_UPDATE, groups);
        tickPhase(b, m, Phase.UPDATE, groups);
        b.append(
                "    /** Runs the spawn behaviours for {@code entity} (after its components were"
                        + " added). */\n");
        b.append("    public void spawn(int entity) {\n");
        for (Behaviour bh : m.ofPhase(Phase.SPAWN)) {
            b.append("        ").append(bh.id()).append("_one(entity);\n");
        }
        b.append("    }\n\n");
        b.append(
                "    /** Runs the despawn behaviours for {@code entity}, then removes its"
                        + " components. */\n");
        b.append("    public void despawn(int entity) {\n");
        for (Behaviour bh : m.ofPhase(Phase.DESPAWN)) {
            b.append("        ").append(bh.id()).append("_one(entity);\n");
        }
        b.append(
                "        for (Store s : stores) {\n"
                        + "            s.remove(entity);\n"
                        + "        }\n"
                        + "    }\n\n");
        b.append(
                "    /** Runs the turn behaviours for {@code entity}. */\n"
                        + "    public void turn(int entity) {\n");
        for (Behaviour bh : m.ofPhase(Phase.TURN)) {
            b.append("        ").append(bh.id()).append("_one(entity);\n");
        }
        b.append("    }\n\n");
        b.append(
                "    /** Runs the trigger behaviours of {@code kind} (1 enter, 2 exit) for {@code"
                        + " entity}. */\n");
        b.append("    public void trigger(int trigger, int entity, int kind) {\n");
        kindSwitch(b, m.ofPhase(Phase.TRIGGER), "trigger, entity, kind");
        b.append("    }\n\n");
        b.append(
                "    /** Dispatches {@code count} physics trigger events, {@code (trigger, entity,"
                        + " kind)} triples. */\n");
        b.append("    public void dispatch(int[] events, int count) {\n");
        b.append("        for (int o = 0, end = count * 3; o < end; o += 3) {\n");
        b.append(
                "            trigger(events[o], events[o + 1], events[o + 2]);\n"
                        + "        }\n"
                        + "    }\n\n");
        b.append(
                "    /** Raises a signal: runs the event behaviours of {@code kind} for {@code"
                        + " entity}. */\n");
        b.append("    public void signal(int kind, int entity, int a, int b) {\n");
        kindSwitch(b, m.ofPhase(Phase.EVENT), "entity, a, b");
        b.append("    }\n\n");
        // Levels.
        b.append(
                "    /** Adds the level's component rows to the entities {@code binding} maps its"
                    + " objects to, then runs the spawn behaviours for each of them; returns the"
                    + " rows applied (D109). */\n");
        b.append(
                "    public int load(dev.jeddy.asset.format.LevelData level,"
                        + " dev.jeddy.components.Levels.Binding binding) {\n");
        b.append(
                "        int applied = dev.jeddy.components.Levels.load(stores, level,"
                        + " binding);\n");
        b.append("        int last = 0;\n");
        b.append("        for (int row = 0; row < level.componentRowCount(); row++) {\n");
        b.append("            int entity = binding.entityOf(level.componentRowObject(row));\n");
        b.append(
                "            if (entity != 0 && entity != last) {\n"
                        + "                spawn(entity);\n"
                        + "                last = entity;\n"
                        + "            }\n"
                        + "        }\n");
        b.append("        return applied;\n    }\n\n");
        b.append(
                "    /** Adds the rows of level object {@code objectId} to {@code entity} (no spawn"
                        + " behaviours); returns the rows applied. */\n");
        b.append(
                "    public int loadObject(dev.jeddy.asset.format.LevelData level, int objectId,"
                        + " int entity, dev.jeddy.components.Levels.Binding binding) {\n");
        b.append(
                "        return dev.jeddy.components.Levels.loadObject(stores, level, objectId,"
                        + " entity, binding);\n"
                        + "    }\n\n");
        // Snapshots.
        b.append(
                "    /** Writes every store (D111). */\n"
                        + "    public void write(SnapshotWriter w) {\n");
        b.append(
                "        w.int32(stores.length);\n"
                        + "        for (Store s : stores) {\n"
                        + "            s.write(w);\n"
                        + "        }\n"
                        + "    }\n\n");
        b.append(
                "    /** Reads what {@link #write} wrote: stores by name, unknown ones skipped."
                        + " */\n");
        b.append(
                "    public void read(SnapshotReader r) {\n"
                        + "        int n = r.int32();\n"
                        + "        for (int i = 0; i < n; i++) {\n");
        b.append(
                "            Store s = store(r.peekString());\n"
                        + "            if (s != null) {\n"
                        + "                s.read(r);\n"
                        + "            } else {\n"
                        + "                Store.skip(r);\n"
                        + "            }\n"
                        + "        }\n"
                        + "    }\n\n");
        // Behaviour bodies.
        for (Behaviour bh : m.behaviours) {
            switch (bh.phase) {
                case FIXED_UPDATE, UPDATE -> {
                    if (bh.parallel) {
                        parallelRange(b, bh);
                    } else {
                        loop(b, bh);
                    }
                }
                default -> one(b, bh);
            }
        }
        b.append("}\n");
        return b.toString();
    }

    private static String viewField(Behaviour bh, int param) {
        return bh.id() + "_v" + param;
    }

    /** Splits a phase's behaviours into maximal runs of parallel and of sequential ones. */
    private static List<List<Behaviour>> runs(List<Behaviour> phase) {
        List<List<Behaviour>> out = new ArrayList<>();
        List<Behaviour> run = null;
        for (Behaviour bh : phase) {
            if (run == null || run.get(0).parallel != bh.parallel) {
                run = new ArrayList<>();
                out.add(run);
            }
            run.add(bh);
        }
        return out;
    }

    private static void tickPhase(
            StringBuilder b, Model m, Phase phase, Map<String, List<Behaviour>> groups) {
        boolean update = phase == Phase.UPDATE;
        List<Integer> stages = m.stages(phase);
        String pass = update ? "dt, alpha" : "dt";
        b.append(
                update
                        ? "    /** Runs the update behaviours of every stage for this frame. */\n"
                                + "    public void update(float dt, float alpha) {\n"
                        : "    /** Runs the fixed-update behaviours of every stage for this tick."
                                + " */\n"
                                + "    public void fixedUpdate(float dt) {\n");
        for (int stage : stages) {
            b.append("        ")
                    .append(update ? "updateStage" : "fixedUpdateStage")
                    .append("(")
                    .append(stage)
                    .append(", ")
                    .append(pass)
                    .append(");\n");
        }
        b.append("    }\n\n");
        b.append(
                update
                        ? "    /** Runs the update behaviours of one stage (a game that interleaves"
                              + " its own systems). */\n"
                              + "    public void updateStage(int stage, float dt, float alpha) {\n"
                              + "        this.dt = dt;\n"
                              + "        this.alpha = alpha;\n"
                        : "    /** Runs the fixed-update behaviours of one stage (a game that"
                                + " interleaves its own systems). */\n"
                                + "    public void fixedUpdateStage(int stage, float dt) {\n"
                                + "        this.dt = dt;\n");
        b.append("        switch (stage) {\n");
        int g = 0;
        for (int stage : stages) {
            b.append("            case ").append(stage).append(" -> {\n");
            for (List<Behaviour> run : runs(m.ofStage(phase, stage))) {
                if (run.get(0).parallel) {
                    String name = phase.json + "Group" + g++;
                    for (Behaviour bh : run) {
                        b.append("                ")
                                .append(bh.id())
                                .append("_drive = ")
                                .append(driveExpression(bh))
                                .append(";\n");
                    }
                    b.append("                if (jobs == null) {\n");
                    for (Behaviour bh : run) {
                        b.append("                    ")
                                .append(bh.id())
                                .append("_range(0, ")
                                .append(bh.id())
                                .append("_drive.size(), 0);\n");
                    }
                    b.append("                } else {\n");
                    for (Behaviour bh : run) {
                        b.append("                    ")
                                .append(name)
                                .append(".setCount(")
                                .append(bh.id())
                                .append("_node, ")
                                .append(bh.id())
                                .append("_drive.size());\n");
                    }
                    b.append("                    ")
                            .append(name)
                            .append(".run(jobs);\n                }\n");
                } else {
                    for (Behaviour bh : run) {
                        b.append("                ").append(bh.id()).append("_loop();\n");
                    }
                }
            }
            b.append("            }\n");
        }
        b.append("            default -> {}\n        }\n    }\n\n");
    }

    private static String driveExpression(Behaviour bh) {
        List<Component> required = bh.required();
        String expr = required.get(0).fieldName();
        for (int i = 1; i < required.size(); i++) {
            expr = "Store.smaller(" + expr + ", " + required.get(i).fieldName() + ")";
        }
        return expr;
    }

    private static void kindSwitch(StringBuilder b, List<Behaviour> behaviours, String args) {
        if (behaviours.isEmpty()) {
            return;
        }
        Map<Integer, List<Behaviour>> byKind = new LinkedHashMap<>();
        for (Behaviour bh : behaviours) {
            byKind.computeIfAbsent(bh.kindValue, k -> new ArrayList<>()).add(bh);
        }
        b.append("        switch (kind) {\n");
        for (Map.Entry<Integer, List<Behaviour>> e : byKind.entrySet()) {
            b.append("            case ").append(e.getKey()).append(" -> {\n");
            for (Behaviour bh : e.getValue()) {
                b.append("                ")
                        .append(bh.id())
                        .append("_one(")
                        .append(args)
                        .append(");\n");
            }
            b.append("            }\n");
        }
        b.append("            default -> {}\n        }\n");
    }

    /** The membership tests, view positioning and call for one entity {@code e}; false to skip. */
    private static void match(
            StringBuilder b, Behaviour bh, String indent, String skip, boolean perThread) {
        match(b, bh, indent, skip, perThread, null);
    }

    /**
     * The membership tests, view positioning and call for one entity {@code e}. With {@code
     * driverRow} set (a loop over the one required store), that store's row is the loop index: no
     * lookup for it.
     */
    private static void match(
            StringBuilder b,
            Behaviour bh,
            String indent,
            String skip,
            boolean perThread,
            String driverRow) {
        int i = 0;
        int r = 0;
        List<Integer> rowOf = new ArrayList<>();
        List<Component> required = bh.required();
        Component driver = driverRow != null && required.size() == 1 ? required.get(0) : null;
        boolean driverUsed = false;
        for (Param p : bh.params) {
            if (p.kind == ParamKind.VIEW || p.kind == ParamKind.MUT) {
                if (p.component == driver && !p.optional && !driverUsed) {
                    driverUsed = true; // the driving store: its row is the loop index
                    b.append(indent)
                            .append("int r")
                            .append(r)
                            .append(" = ")
                            .append(driverRow)
                            .append(";\n");
                    rowOf.add(r++);
                    i++;
                    continue;
                }
                b.append(indent)
                        .append("int r")
                        .append(r)
                        .append(" = ")
                        .append(p.component.fieldName())
                        .append(".indexOf(e);\n");
                if (!p.optional) {
                    b.append(indent)
                            .append("if (r")
                            .append(r)
                            .append(" < 0) {\n")
                            .append(indent)
                            .append("    ")
                            .append(skip)
                            .append("\n")
                            .append(indent)
                            .append("}\n");
                }
                rowOf.add(r++);
            } else {
                rowOf.add(-1);
            }
            i++;
        }
        for (Component w : bh.without) {
            b.append(indent)
                    .append("if (")
                    .append(w.fieldName())
                    .append(".has(e)) {\n")
                    .append(indent)
                    .append("    ")
                    .append(skip)
                    .append("\n")
                    .append(indent)
                    .append("}\n");
        }
        i = 0;
        for (Param p : bh.params) {
            if (p.kind == ParamKind.VIEW || p.kind == ParamKind.MUT) {
                b.append(indent)
                        .append(viewField(bh, i))
                        .append(perThread ? "[thread]" : "")
                        .append(".at(")
                        .append(p.component.fieldName())
                        .append(", r")
                        .append(rowOf.get(i))
                        .append(");\n");
            }
            i++;
        }
        b.append(indent).append(bh.owner).append(".").append(bh.method).append("(");
        i = 0;
        for (Param p : bh.params) {
            b.append(i > 0 ? ", " : "");
            switch (p.kind) {
                case VIEW, MUT -> b.append(viewField(bh, i)).append(perThread ? "[thread]" : "");
                case DT -> b.append("dt");
                case ALPHA -> b.append("alpha");
                case ENTITY -> b.append("e");
                case TRIGGER -> b.append("trigger");
                case KIND -> b.append("kind");
                case A -> b.append("a");
                case B -> b.append("b");
                case SINGLETON -> b.append(p.field);
            }
            i++;
        }
        b.append(");\n");
    }

    private static void loop(StringBuilder b, Behaviour bh) {
        b.append("    private void ").append(bh.id()).append("_loop() {\n");
        b.append("        Store drive = ").append(driveExpression(bh)).append(";\n");
        b.append("        float dt = this.dt;\n");
        if (bh.phase == Phase.UPDATE) {
            b.append("        float alpha = this.alpha;\n");
        }
        b.append("        for (int i = drive.size() - 1; i >= 0; i--) {\n");
        b.append(
                "            if (i >= drive.size()) {\n"
                        + "                continue; // rows went away under the loop\n"
                        + "            }\n");
        b.append("            int e = drive.entityAt(i);\n");
        match(b, bh, "            ", "continue;", false, "i");
        b.append("        }\n    }\n\n");
    }

    private static void parallelRange(StringBuilder b, Behaviour bh) {
        b.append("    private void ")
                .append(bh.id())
                .append("_range(int start, int end, int thread) {\n");
        b.append("        Store drive = ").append(bh.id()).append("_drive;\n");
        b.append("        float dt = this.dt;\n");
        if (bh.phase == Phase.UPDATE) {
            b.append("        float alpha = this.alpha;\n");
        }
        b.append("        for (int i = start; i < end; i++) {\n");
        b.append("            int e = drive.entityAt(i);\n");
        match(b, bh, "            ", "continue;", true, "i");
        b.append("        }\n    }\n\n");
    }

    private static void one(StringBuilder b, Behaviour bh) {
        String args =
                switch (bh.phase) {
                    case TRIGGER -> "int trigger, int e, int kind";
                    case EVENT -> "int e, int a, int b";
                    default -> "int e";
                };
        b.append("    private void ").append(bh.id()).append("_one(").append(args).append(") {\n");
        match(b, bh, "        ", "return;", false);
        b.append("    }\n\n");
    }
}
