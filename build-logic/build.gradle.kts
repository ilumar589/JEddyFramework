import org.jetbrains.kotlin.gradle.dsl.JvmTarget
import java.util.Properties

plugins {
    `kotlin-dsl`
    `maven-publish`
}

// The plugins are published with the framework (TASKS M11-05) as dev.jeddy:jeddy-gradle-plugins
// plus a marker per plugin id, at the framework version: ../gradle.properties, or -Pjeddy.version
// on release builds. dev.jeddy.game and dev.jeddy.assets resolve the cooker and the natives at
// that version (dev.jeddy.gradle.JEDDY_VERSION).
val jeddyVersion: Provider<String> = providers.gradleProperty("jeddy.version").orElse(
    providers.fileContents(layout.projectDirectory.file("../gradle.properties")).asText.map { text ->
        Properties().apply { load(text.reader()) }.getProperty("jeddy.version")
            ?: throw GradleException("jeddy.version is missing from gradle.properties")
    },
)

group = "dev.jeddy"
version = jeddyVersion.get()

dependencies {
    implementation(libs.spotless.gradle)
}

// Build logic runs inside the Gradle daemon (JDK 27 on CI). Pin both compilers to the same
// bytecode level so Kotlin and Java targets stay consistent whatever JDK runs Gradle.
java {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
}

tasks.withType<JavaCompile>().configureEach {
    options.release = 17
}

kotlin {
    compilerOptions {
        jvmTarget = JvmTarget.JVM_17
    }
}

val generateJeddyVersion = tasks.register("generateJeddyVersion") {
    val value = jeddyVersion
    val outputDir = layout.buildDirectory.dir("generated/sources/jeddyVersion")
    inputs.property("version", value)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().file("dev/jeddy/gradle/JeddyVersion.kt").asFile
        file.parentFile.mkdirs()
        file.writeText(
            """
            |package dev.jeddy.gradle
            |
            |/** The Jeddy version these plugins belong to (generated by build-logic/build.gradle.kts). */
            |const val JEDDY_VERSION = "${value.get()}"
            |""".trimMargin(),
        )
    }
}

kotlin.sourceSets.named("main") {
    kotlin.srcDir(generateJeddyVersion)
}

val repoUrl = "https://github.com/ilumar589/JEddyFramework"
val publishUrl = providers.gradleProperty("jeddy.publish.url")
    .orElse(repoUrl.replace("https://github.com/", "https://maven.pkg.github.com/"))
val publishUser = providers.environmentVariable("GITHUB_ACTOR").orElse(providers.gradleProperty("gpr.user"))
val publishKey = providers.environmentVariable("GITHUB_TOKEN").orElse(providers.gradleProperty("gpr.key"))

publishing {
    publications.withType<MavenPublication>().configureEach {
        if (name == "pluginMaven") {
            artifactId = "jeddy-gradle-plugins"
        }
        pom {
            url = repoUrl
            licenses {
                license {
                    name = "MIT License"
                    url = "https://opensource.org/license/mit"
                }
            }
            scm {
                url = repoUrl
                connection = "scm:git:$repoUrl.git"
            }
        }
    }
    repositories {
        if (publishUser.isPresent && publishKey.isPresent) {
            maven {
                name = "GitHubPackages"
                url = uri(publishUrl.get())
                credentials {
                    username = publishUser.get()
                    password = publishKey.get()
                }
            }
        }
    }
}
